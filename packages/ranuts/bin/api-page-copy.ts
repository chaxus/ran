/**
 * Per-language chrome for the generated ranuts API reference.
 *
 * What is *not* here: the per-symbol signatures and descriptions. Those are extracted
 * verbatim from source JSDoc, which is written in English by convention — translating them
 * at generation time would mean maintaining a second copy of every doc comment, exactly the
 * drift this generator exists to prevent. Each page says so in its own language.
 *
 * The language list mirrors `packages/docs/.vitepress/langs/locales.ts`. It is duplicated
 * rather than imported because `packages/ranuts` does not depend on `packages/docs`, but the
 * duplication is enforced: `pnpm -F docs check:langs` fails when a language is missing a page.
 */

export const DOC_LOCALE_DIRS = ['', 'cn', 'ja', 'es', 'pt', 'ko', 'de', 'fa'] as const;
export type DocLocaleDir = (typeof DOC_LOCALE_DIRS)[number];

export type Kind = 'function' | 'class' | 'interface' | 'type' | 'enum' | 'const' | 'namespace' | 'other';

/** The canonical (English) runtime strings, used as keys into each language's map. */
export type RuntimeKey = 'browser + node' | 'service worker only' | 'node only' | 'browser only' | 'browser';

export interface ApiPageCopy {
  title: string;
  description: (total: number, entries: number) => string;
  heading: string;
  /** The two orientation paragraphs; `claudeLink` differs between tarball and site. */
  intro: (claudeLink: string) => string[];
  totalLine: (total: number, entries: number) => string;
  tocHeading: string;
  /** One TOC row. `count` is the number of exports from that entry point. */
  tocItem: (row: { subpath: string; anchor: string; blurb: string; runtime: string; count: number }) => string;
  /** The metadata line under each `## \`ranuts/…\`` heading. */
  sectionMeta: (row: { blurb: string; runtime: string; file: string }) => string;
  kindTitles: Record<Kind, string>;
  runtimes: Record<RuntimeKey, string>;
  /** Entry-point blurbs, keyed by subpath. */
  blurbs: Record<string, string>;
}

